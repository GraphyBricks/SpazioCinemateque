const path = require('path')
const Database = require('better-sqlite3')
const { Client } = require('pg')

const sqlite = new Database(path.join(process.cwd(), 'data', 'spazio.db'), { readonly: true })
const connectionString = (process.env.DATABASE_URL_UNPOOLED || process.env.DATABASE_URL)
  ?.replace('sslmode=require', 'sslmode=verify-full')

if (!connectionString) {
  throw new Error('DATABASE_URL_UNPOOLED or DATABASE_URL is required')
}

const postgres = new Client({ connectionString })

const schema = `
  CREATE TABLE IF NOT EXISTS movies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    director TEXT,
    genre TEXT,
    poster_url TEXT,
    maps_url TEXT,
    duration INTEGER,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );
  CREATE TABLE IF NOT EXISTS events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    date TEXT NOT NULL,
    time TEXT NOT NULL,
    image TEXT,
    type TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );
  CREATE TABLE IF NOT EXISTS screenings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id INTEGER NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    event_type TEXT NOT NULL DEFAULT 'film',
    date TEXT NOT NULL,
    time TEXT NOT NULL,
    room TEXT NOT NULL,
    total_seats INTEGER NOT NULL DEFAULT 90,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );
  CREATE TABLE IF NOT EXISTS seats (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screening_id INTEGER NOT NULL REFERENCES screenings(id) ON DELETE CASCADE,
    row TEXT NOT NULL,
    seat_number INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'available',
    type TEXT NOT NULL DEFAULT 'standard',
    UNIQUE (screening_id, row, seat_number)
  );
  CREATE TABLE IF NOT EXISTS reservations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screening_id INTEGER NOT NULL REFERENCES screenings(id) ON DELETE CASCADE,
    customer_name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    confirmation_code TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'confirmed',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );
  CREATE TABLE IF NOT EXISTS reservation_seats (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id INTEGER NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
    seat_id INTEGER NOT NULL REFERENCES seats(id) ON DELETE CASCADE,
    UNIQUE (reservation_id, seat_id)
  );
  CREATE TABLE IF NOT EXISTS gallery_photos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image TEXT NOT NULL,
    caption TEXT,
    date TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );
  CREATE INDEX IF NOT EXISTS screenings_date_time_idx ON screenings(date, time);
  CREATE INDEX IF NOT EXISTS seats_screening_status_idx ON seats(screening_id, status);
  CREATE INDEX IF NOT EXISTS reservations_screening_idx ON reservations(screening_id);
`

const tables = [
  {
    name: 'movies',
    columns: ['id', 'title', 'description', 'director', 'genre', 'poster_url', 'maps_url', 'duration', 'created_at'],
  },
  {
    name: 'events',
    columns: ['id', 'title', 'description', 'date', 'time', 'image', 'type', 'created_at'],
  },
  {
    name: 'screenings',
    columns: ['id', 'movie_id', 'event_type', 'date', 'time', 'room', 'total_seats', 'created_at'],
  },
  {
    name: 'seats',
    columns: ['id', 'screening_id', 'row', 'seat_number', 'status', 'type'],
  },
  {
    name: 'reservations',
    columns: ['id', 'screening_id', 'customer_name', 'email', 'phone', 'confirmation_code', 'status', 'created_at'],
  },
  {
    name: 'reservation_seats',
    columns: ['id', 'reservation_id', 'seat_id'],
  },
  {
    name: 'gallery_photos',
    columns: ['id', 'image', 'caption', 'date', 'created_at'],
  },
]

async function insertRows(table, rows) {
  for (const row of rows) {
    const placeholders = table.columns.map((_, index) => '$' + (index + 1)).join(', ')
    const values = table.columns.map((column) => row[column])
    await postgres.query(
      `INSERT INTO ${table.name} (${table.columns.join(', ')}) VALUES (${placeholders})`,
      values
    )
  }
}

async function run() {
  await postgres.connect()
  await postgres.query(schema)

  const populated = await postgres.query(`
    SELECT
      (SELECT count(*) FROM movies) +
      (SELECT count(*) FROM screenings) +
      (SELECT count(*) FROM reservations) +
      (SELECT count(*) FROM events) +
      (SELECT count(*) FROM gallery_photos) AS count
  `)

  if (Number(populated.rows[0].count) > 0) {
    throw new Error('Neon already contains application data; migration stopped without changing it.')
  }

  await postgres.query('BEGIN')
  try {
    for (const table of tables) {
      const rows = sqlite.prepare(`SELECT ${table.columns.join(', ')} FROM ${table.name} ORDER BY id`).all()
      await insertRows(table, rows)
      console.log(`Migrated ${rows.length} rows into ${table.name}`)
    }

    for (const table of tables) {
      await postgres.query(
        `SELECT setval(pg_get_serial_sequence($1, 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM ${table.name}`,
        [table.name]
      )
    }

    await postgres.query('COMMIT')
  } catch (error) {
    await postgres.query('ROLLBACK')
    throw error
  }

  const summary = await postgres.query(`
    SELECT
      (SELECT count(*)::int FROM movies) AS movies,
      (SELECT count(*)::int FROM screenings) AS screenings,
      (SELECT count(*)::int FROM seats) AS seats,
      (SELECT count(*)::int FROM reservations) AS reservations
  `)
  console.log('Neon migration complete:', summary.rows[0])
}

run()
  .catch((error) => {
    console.error(error.message)
    process.exitCode = 1
  })
  .finally(async () => {
    sqlite.close()
    await postgres.end()
  })
